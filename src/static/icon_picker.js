  const body = document.body;
  const targetId = body.dataset.pickerTarget || "";
  const mode = body.dataset.pickerMode || "replace";
  const tabsEl = document.querySelector("[data-icon-tabs]");
  const gridEl = document.querySelector("[data-icon-grid]");
  const searchEl = document.querySelector(".icon-picker-search");
  const selectedEl = document.querySelector("[data-selected-icon]");
  let activeGroup = GROUPS[0].id;

  function allItems() {
    const seen = new Set();
    const items = [];
    GROUPS.forEach((group) => {
      group.items.forEach((item) => {
        if (!seen.has(item.icon)) {
          seen.add(item.icon);
          items.push({ ...item, groupLabel: group.label });
        }
      });
    });
    return items;
  }

  function activeItems() {
    const group = GROUPS.find((item) => item.id === activeGroup) || GROUPS[0];
    return group.items.map((item) => ({ ...item, groupLabel: group.label }));
  }

  function filteredItems() {
    const query = (searchEl.value || "").trim().toLowerCase();
    const source = query ? allItems() : activeItems();
    if (!query) {
      return source;
    }
    return source.filter((item) => {
      return item.icon.includes(query) || item.terms.includes(query) || item.groupLabel.toLowerCase().includes(query);
    });
  }

  function renderTabs() {
    tabsEl.innerHTML = "";
    GROUPS.forEach((group) => {
      const button = document.createElement("button");
      button.type = "button";
      button.className = group.id === activeGroup ? "active" : "";
      button.textContent = group.label;
      button.addEventListener("click", () => {
        activeGroup = group.id;
        searchEl.value = "";
        render();
      });
      tabsEl.appendChild(button);
    });
  }

  function chooseIcon(icon) {
    if (selectedEl) {
      selectedEl.textContent = icon;
    }
    if (window.opener && !window.opener.closed && typeof window.opener.LifePIMIconPickerSelect === "function") {
      window.opener.LifePIMIconPickerSelect({ icon, targetId, mode });
      window.setTimeout(() => window.close(), 100);
      return;
    }
    if (navigator.clipboard) {
      navigator.clipboard.writeText(icon).catch(() => {});
    }
  }

  function renderGrid() {
    const items = filteredItems();
    gridEl.innerHTML = "";
    if (!items.length) {
      const empty = document.createElement("div");
      empty.className = "icon-picker-empty";
      empty.textContent = "No matching icons.";
      gridEl.appendChild(empty);
      return;
    }
    items.forEach((item) => {
      const button = document.createElement("button");
      button.type = "button";
      button.className = "icon-picker-choice";
      button.textContent = item.icon;
      button.title = item.terms ? `${item.icon} ${item.terms}` : item.icon;
      button.addEventListener("click", () => chooseIcon(item.icon));
      gridEl.appendChild(button);
    });
  }

  function render() {
    renderTabs();
    renderGrid();
  }

  searchEl.addEventListener("input", renderGrid);
  render();
  searchEl.focus();
